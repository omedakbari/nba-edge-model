"""Diagnose only: how far ESPN's per-side `updated_at` sits from our capture time, for rejected sides.

Reads data/quote_snapshots/*.json (the ESPN prop snapshots; data/live_snapshots holds only the
scoreboard/injuries/rosters). delta = updated_at - captured_at, in 5-minute bins:
negative = the quote claims to be older than our capture (stale beyond 15 min),
positive = the quote claims to be from the future. Changes nothing; the eligibility gate is untouched.

Run: ./venv/bin/python scripts/report_espn_timestamps.py [--since 2026-11-01] [--out docs/findings/espn-timestamps.md]
"""
import argparse
import json
import math
import statistics
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLIP_MIN = 180          # deltas beyond ±3 h go in one overflow bin each side


def ts(s):
    return datetime.fromisoformat(s.replace('Z', '+00:00'))


def bin_of(delta_s):
    m = delta_s / 60
    if m >= CLIP_MIN:
        return CLIP_MIN
    if m < -CLIP_MIN:
        return -CLIP_MIN - 5
    return int(math.floor(m / 5) * 5)


def label(b):
    if b == CLIP_MIN:
        return f'>= +{CLIP_MIN} min'
    if b == -CLIP_MIN - 5:
        return f'< -{CLIP_MIN} min'
    return f'[{b:+d}, {b + 5:+d}) min'


def collect(since):
    bins = defaultdict(Counter)          # reason -> bin -> n
    by_book = Counter()
    per_day = defaultdict(Counter)
    extra = {'future_min': [], 'future_vs_tip': [], 'stale_h': []}
    files = []
    for path in sorted((ROOT / 'data/quote_snapshots').glob('*.json')):
        day = path.name[:10]
        if since and day < since:
            continue
        snap = json.loads(path.read_text())
        captured = snap.get('captured_at')
        rej = snap.get('rejected_quotes') or []
        starts = {e['id']: e.get('date') for e in (snap.get('scoreboard') or {}).get('events', [])}
        files.append((path.name, captured, len(snap.get('rows') or []), len(rej)))
        for r in rej:
            reason = r.get('reason')
            per_day[day][reason] += 1
            if not r.get('updated_at') or not captured:
                bins[reason]['n/a'] += 1
                continue
            try:
                delta = (ts(r['updated_at']) - ts(captured)).total_seconds()
            except (TypeError, ValueError):
                bins[reason]['n/a'] += 1
                continue
            bins[reason][bin_of(delta)] += 1
            if delta > 0:
                extra['future_min'].append(delta / 60)
                if starts.get(r.get('event_id')):
                    extra['future_vs_tip'].append((ts(r['updated_at']) - ts(starts[r['event_id']])).total_seconds() / 60)
            elif delta < -CLIP_MIN * 60:
                extra['stale_h'].append(-delta / 3600)
            by_book[(r.get('book'), reason)] += 1
    return files, bins, by_book, per_day, extra


def render(files, bins, by_book, per_day, extra):
    out = ['# ESPN prop timestamps: rejected sides, updated_at - captured_at', '',
           f'Generated by `scripts/report_espn_timestamps.py` on {datetime.now().date()}. Diagnose only:',
           'the eligibility gate (`src/betting/quote_quality.py`, 15 min max age, no future stamps) is unchanged.',
           '',
           'Source: `data/quote_snapshots/*.json` (`rejected_quotes` vs the snapshot `captured_at`).',
           '`data/live_snapshots` holds only scoreboard / injuries / rosters, no prop sides.',
           'Negative = older than capture, positive = stamped in the future. 5-minute bins, clipped at ±3 h.', '',
           '## Summary', '']
    fm, ft, sh = extra['future_min'], extra['future_vs_tip'], extra['stale_h']
    if fm:
        books = sorted({b for b, _ in by_book})
        out.append(f'- Books among rejected sides: {", ".join(map(str, books))}. ESPN\'s prop feed carries only '
                   'DraftKings, so there is no second ESPN book to fall back on.')
        out.append(f'- Future stamps: {len(fm)} sides, all between 0 and {max(fm):.1f} min ahead of capture, spread '
                   f'roughly evenly (median {statistics.median(fm):.0f} min). No single offset like +60 or +180 min, '
                   'so it is not a timezone mislabel.')
    if ft:
        near = sum(-5 <= x <= 5 for x in ft) / len(ft)
        out.append(f'- Future stamps vs tip: updated_at - tip ranges {min(ft):.0f} to {max(ft):.0f} min '
                   f'(median {statistics.median(ft):.0f}); only {near:.1%} are within 5 min of tip, so '
                   'they are not tip-time placeholders either.')
    if sh:
        q = statistics.quantiles(sh, n=10)
        out.append(f'- Stale: {len(sh)} sides older than 3 h; their age p10 {q[0]:.1f} h, median '
                   f'{statistics.median(sh):.1f} h, p90 {q[-1]:.1f} h, max {max(sh):.1f} h. DraftKings leaves '
                   'many sides unrefreshed for most of a day, so loosening the 15-min rule would admit old prices.')
    out += ['- Conclusion: the ESPN DraftKings feed cannot price a same-day card. Use the worker\'s PropLine '
            'consensus / no-vig and Kalshi (Step 1b `prop_worker.slate --card`) instead. Gate unchanged.', '',
           '## Snapshots read', '', '| file | captured_at (UTC) | rows | rejected |', '|---|---|---|---|']
    out += [f'| {f} | {c} | {n} | {r} |' for f, c, n, r in files]
    out += ['', '## Rejections per slate day', '', '| day | ' + ' | '.join(
        reasons := sorted({k for c in per_day.values() for k in c})) + ' |',
        '|---|' + '---|' * len(reasons)]
    out += [f'| {d} | ' + ' | '.join(str(per_day[d][k]) for k in reasons) + ' |' for d in sorted(per_day)]
    for reason, c in sorted(bins.items()):
        total = sum(c.values())
        out += ['', f'## {reason} ({total} sides)', '', '| delta bin | sides | share |', '|---|---|---|']
        for b in sorted((k for k in c if k != 'n/a')):
            out.append(f'| {label(b)} | {c[b]} | {c[b] / total:.1%} |')
        if c.get('n/a'):
            out.append(f'| no timestamp | {c["n/a"]} | {c["n/a"] / total:.1%} |')
    out += ['', '## By book', '', '| book | reason | sides |', '|---|---|---|']
    out += [f'| {b} | {r} | {n} |' for (b, r), n in sorted(by_book.items(), key=lambda kv: -kv[1])]
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--since', default='2026-11-01')
    ap.add_argument('--out', default=str(ROOT / 'docs/findings/espn-timestamps.md'))
    a = ap.parse_args()
    text = render(*collect(a.since))
    print(text)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text)


if __name__ == '__main__':
    main()
